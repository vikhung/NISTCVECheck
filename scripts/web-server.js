function _makeProxyFetch(proxyUrl, skipTls) {
    const _tls  = require('tls');
    const proxy = new URL(proxyUrl);
    const proxyAuth = proxy.username
        ? 'Basic ' + Buffer.from(
            `${decodeURIComponent(proxy.username)}:${decodeURIComponent(proxy.password)}`
          ).toString('base64')
        : null;

    return function proxyFetch(urlStr, opts = {}) {
        const target = new URL(urlStr);
        const { headers: reqHeaders = {}, signal } = opts;
        return new Promise((resolve, reject) => {
            if (signal?.aborted)
                return reject(Object.assign(new Error('The operation was aborted'), { name: 'AbortError' }));

            const connectHdrs = { Host: `${target.hostname}:443` };
            if (proxyAuth) connectHdrs['Proxy-Authorization'] = proxyAuth;

            const cReq = http.request({
                host: proxy.hostname, port: +proxy.port || 80,
                method: 'CONNECT', path: `${target.hostname}:443`,
                headers: connectHdrs,
            });
            const onAbort = () => cReq.destroy(Object.assign(new Error('The operation was aborted'), { name: 'AbortError' }));
            signal?.addEventListener('abort', onAbort, { once: true });

            cReq.on('error', err => { signal?.removeEventListener('abort', onAbort); reject(err); });
            cReq.on('connect', (res, socket) => {
                signal?.removeEventListener('abort', onAbort);
                if (res.statusCode !== 200) {
                    socket.destroy();
                    return reject(new Error(`Proxy CONNECT failed: HTTP ${res.statusCode}`));
                }
                const sock = _tls.connect({
                    socket, host: target.hostname, servername: target.hostname,
                    rejectUnauthorized: !skipTls,
                });
                sock.on('error', reject);
                sock.on('secureConnect', () => {
                    const reqPath = (target.pathname || '/') + target.search;
                    const hlines  = Object.entries(reqHeaders).map(([k, v]) => `${k}: ${v}`).join('\r\n');
                    sock.write(
                        `GET ${reqPath} HTTP/1.1\r\nHost: ${target.hostname}\r\n` +
                        (hlines ? hlines + '\r\n' : '') +
                        'Connection: close\r\n\r\n'
                    );
                    const bufs = [];
                    sock.on('data', c => bufs.push(Buffer.isBuffer(c) ? c : Buffer.from(c)));
                    sock.on('end', () => {
                        try {
                            const raw    = Buffer.concat(bufs);
                            const sep    = raw.indexOf('\r\n\r\n');
                            if (sep < 0) throw new Error('Malformed HTTP response');
                            const status = parseInt(raw.slice(0, raw.indexOf('\r\n')).toString('ascii').split(' ')[1], 10);
                            const hdrs   = raw.slice(0, sep).toString('ascii').toLowerCase();
                            let   body   = raw.slice(sep + 4);
                            if (hdrs.includes('transfer-encoding: chunked')) {
                                const parts = [];
                                let pos = 0;
                                while (pos < body.length) {
                                    const nl   = body.indexOf('\r\n', pos);
                                    if (nl < 0) break;
                                    const size = parseInt(body.slice(pos, nl).toString('ascii').trim(), 16);
                                    if (!size) break;
                                    parts.push(body.slice(nl + 2, nl + 2 + size));
                                    pos = nl + 2 + size + 2;
                                }
                                body = Buffer.concat(parts);
                            }
                            const bodyStr = body.toString('utf8');
                            resolve({ ok: status >= 200 && status < 300, status, json: () => Promise.resolve(JSON.parse(bodyStr)) });
                        } catch (e) { reject(e); }
                    });
                });
            });
            cReq.end();
        });
    };
}

